// Appwrite deploys each Function and Site folder on its own, so shared logic in core/ is
// copied into functions/*/src/core and web/src/core before every deploy. Edit core/, never the copies.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const files = fs.readdirSync(path.join(root, 'core')).filter((f) => f.endsWith('.js') && !f.endsWith('.test.js'));
const targets = [
  ...['compute-stats', 'fair-range'].map((fn) => path.join(root, 'functions', fn, 'src', 'core')),
  path.join(root, 'web', 'src', 'core'),
];

for (const dir of targets) {
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  for (const f of files) {
    const src = fs.readFileSync(path.join(root, 'core', f), 'utf8');
    fs.writeFileSync(path.join(dir, f), `// GENERATED by scripts/sync-core.mjs from core/${f}. Do not edit.\n${src}`);
  }
}
console.log(`synced ${files.join(', ')} → ${targets.length} targets`);
